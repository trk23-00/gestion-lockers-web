CREATE TABLE rol (
  id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nivel INTEGER NOT NULL UNIQUE CHECK (nivel BETWEEN 1 AND 4),
  nombre_rol VARCHAR(100) NOT NULL UNIQUE
);
INSERT INTO rol(nivel,nombre_rol) VALUES
