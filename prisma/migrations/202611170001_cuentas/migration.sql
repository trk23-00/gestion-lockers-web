CREATE TABLE configuracion (
  id INTEGER PRIMARY KEY DEFAULT 1 CHECK (id=1),
  importe_inicial NUMERIC(12,2) NOT NULL DEFAULT 2 CHECK (importe_inicial>0),
  recargo_semanal NUMERIC(12,2) NOT NULL DEFAULT 2 CHECK (recargo_semanal>0),
  dias_iniciales INTEGER NOT NULL DEFAULT 7 CHECK (dias_iniciales BETWEEN 1 AND 365),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
